import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rm, stat, writeFile } from 'node:fs/promises';
import { extname, join, resolve } from 'node:path';
import {
  BadRequestException,
  Injectable,
  NotFoundException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import {
  FILE_NOT_FOUND_ERROR,
  FILE_NOT_PROVIDED_ERROR,
  FILE_TYPE_ERROR,
  FILES_ROUTE,
  FileKind,
  ImageType,
} from './file.constants';
import { detectImageType } from './image-type';

export interface StoredFile {
  id: string;
  path: string;
  kind: FileKind;
  mimeType: string;
  size: number;
}

const MIME_TYPES: Record<string, string> = {
  [`.${ImageType.Png.extension}`]: ImageType.Png.mimeType,
  [`.${ImageType.Jpeg.extension}`]: ImageType.Jpeg.mimeType,
};

@Injectable()
export class FileService {
  constructor(private readonly configService: ConfigService) {}

  public async save(
    file: Express.Multer.File | undefined,
    kind: FileKind
  ): Promise<StoredFile> {
    if (!file) {
      throw new BadRequestException(FILE_NOT_PROVIDED_ERROR);
    }

    const imageType = detectImageType(file.buffer);
    if (!imageType) {
      throw new BadRequestException(FILE_TYPE_ERROR);
    }

    const id = `${randomUUID()}.${imageType.extension}`;
    await mkdir(this.getUploadDirectory(), { recursive: true });
    await writeFile(this.getFilePath(id), file.buffer);

    return {
      id,
      path: `${FILES_ROUTE}/${id}`,
      kind,
      mimeType: imageType.mimeType,
      size: file.size,
    };
  }

  public async read(
    id: string
  ): Promise<{ content: Buffer; mimeType: string }> {
    await this.checkFileExists(id);

    return {
      content: await readFile(this.getFilePath(id)),
      mimeType: MIME_TYPES[extname(id)],
    };
  }

  public async delete(id: string): Promise<void> {
    await this.checkFileExists(id);
    await rm(this.getFilePath(id));
  }

  private async checkFileExists(id: string): Promise<void> {
    try {
      await stat(this.getFilePath(id));
    } catch {
      throw new NotFoundException(FILE_NOT_FOUND_ERROR);
    }
  }

  // Only IDs generated by the service reach this point (see FileIdPipe),
  // so a path cannot leave the upload directory
  private getFilePath(id: string): string {
    return join(this.getUploadDirectory(), id);
  }

  private getUploadDirectory(): string {
    return resolve(
      process.cwd(),
      this.configService.getOrThrow<string>('file.uploadDirectory')
    );
  }
}
